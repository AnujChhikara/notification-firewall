package com.anuj.notificationfirewall.ai.ask

sealed interface SqlVerdict {
    data class Allowed(val sql: String) : SqlVerdict
    data class Rejected(val reason: String) : SqlVerdict
}

/**
 * Gate between a model-authored string and the user's database.
 *
 * The posture is allow-list, not deny-list: the statement must be a single
 * SELECT, over four named tables, with a bounded LIMIT, and — unless the user
 * opted in for this query — mentioning neither content column anywhere, not
 * even in a WHERE clause, since a filter on text leaks it one row at a time.
 * Anything not positively recognised is rejected.
 *
 * A deny-list would be the wrong shape here. The input is generated by a model
 * that can be steered by the contents of notifications it has read, so the
 * question is not "have I thought of every bad statement" but "have I permitted
 * only the good ones".
 *
 * Double quotes, backticks and square brackets are rejected outright rather
 * than masked like single-quoted literals: SQLite accepts any of them as
 * identifier quoting, and an identifier can contain almost anything —
 * including a `(` or `,` that would defeat the paren-depth and comma-join
 * checks below. Nothing this feature's schema needs requires quoting an
 * identifier, so the whole class is refused up front.
 *
 * The star-projection check reads the output of a single top-level parse
 * ([findTopLevelProjection]) instead of re-deriving "where does the real
 * projection end" with its own regex — two separate leaks in earlier
 * revisions of this file traced back to exactly that kind of re-derivation
 * going wrong (a whitespace assumption between the projection and FROM, and
 * a first-`from`-anywhere scan that landed inside a subquery's parentheses
 * and truncated the projection before the real star was ever seen).
 *
 * The comma-join check ([hasCommaInAnyFromClause]) deliberately does *not*
 * share that "top level" notion. A comma join can hide inside any `FROM`
 * anywhere in the statement — the outermost one, or one nested inside a
 * WHERE/HAVING subquery, or one nested inside a subquery embedded in the
 * projection — and each occurrence needs the same check applied to its own
 * local table clause, independent of how deeply it's nested. Tying comma
 * detection to a single "the" top-level FROM (as an earlier revision did)
 * is what let a comma join inside a projection subquery defeat the guard
 * entirely, since the scanner started counting parenthesis depth from the
 * position of first `from` found — which could itself be inside a subquery
 * — rather than from each occurrence's own start.
 */
object SqlValidator {

    const val MAX_LIMIT = 500

    private val KNOWN_TABLES = setOf("notifications", "verdict_cache", "sender_bias", "overrides")
    private val CONTENT_COLUMNS = setOf("title", "text")

    private val FORBIDDEN = listOf(
        "insert", "update", "delete", "drop", "alter", "create", "replace",
        "pragma", "attach", "detach", "vacuum", "reindex", "trigger",
        "sqlite_master", "sqlite_temp_master", "sqlite_schema", "load_extension",
    )
    private val FORBIDDEN_PATTERNS = FORBIDDEN.map { it to Regex("""\b${Regex.escape(it)}\b""") }

    // A compound SELECT (UNION[ALL]/INTERSECT/EXCEPT) has more than one
    // projection, and this validator only ever inspects the first branch's
    // projection for a leaking star -- the Ask tab has no need to emit one,
    // so the whole class is refused rather than taught to the parser.
    private val COMPOUND_KEYWORDS = listOf("union", "intersect", "except")
    private val COMPOUND_PATTERNS = COMPOUND_KEYWORDS.map { it to Regex("""\b${Regex.escape(it)}\b""") }

    private val QUOTE_CHARS = charArrayOf('"', '`', '[', ']')

    private val SELECT_START = Regex("""^select\b""", RegexOption.IGNORE_CASE)
    private val FROM_OR_JOIN = Regex("""\b(?:from|join)\s+([a-z_][a-z0-9_]*)""", RegexOption.IGNORE_CASE)
    private val FROM_OR_JOIN_PAREN = Regex("""\b(?:from|join)\s*\(""", RegexOption.IGNORE_CASE)
    private val FROM_KEYWORD = Regex("""\bfrom\b""", RegexOption.IGNORE_CASE)
    private val CLAUSE_STOP_WORDS = setOf("where", "group", "having", "order", "limit")
    private val FENCE = Regex("""^```(?:sql)?\s*|\s*```$""", RegexOption.IGNORE_CASE)

    // Exactly one LIMIT is tolerated, and it must be the final clause of the
    // statement: `LIMIT <n>` optionally followed by `OFFSET <n>`. Anchoring to
    // the end of the string rules out `LIMIT 1, 100000` (SQLite's
    // offset,count form — the number that actually bounds the result set is
    // the *second* one) and `LIMIT 5*1000` (an expression, not a bare
    // integer), both of which a non-anchored "first digits after limit"
    // capture would misread as the small, safe-looking number.
    private val LIMIT_KEYWORD = Regex("""\blimit\b""", RegexOption.IGNORE_CASE)
    private val LIMIT_CLAUSE = Regex(
        """\blimit\s+(\d+)\s*(?:offset\s+\d+\s*)?$""",
        setOf(RegexOption.IGNORE_CASE),
    )

    // Quoted string literals can contain arbitrary text ('com.title.app') that
    // must not be mistaken for a keyword or column reference. Blank them out
    // (preserving length, so other offsets/regexes are unaffected) before any
    // keyword or column-name check.
    private val STRING_LITERAL = Regex("""'[^']*'""")
    private fun maskLiterals(s: String) = STRING_LITERAL.replace(s) { " ".repeat(it.value.length) }

    private fun hasUnbalancedParens(text: String): Boolean {
        var depth = 0
        for (c in text) {
            when (c) {
                '(' -> depth++
                ')' -> {
                    depth--
                    if (depth < 0) return true
                }
            }
        }
        return depth != 0
    }

    // A leading DISTINCT/ALL quantifier is a SELECT-level modifier, not part
    // of any projected column; it must be stripped before the projection is
    // inspected for a star, or `SELECT DISTINCT *` would fail to be
    // recognised as `SELECT *` in disguise.
    private val QUANTIFIER_PREFIX = Regex("""^\s*(?:distinct|all)\b\s*""", RegexOption.IGNORE_CASE)

    // A single top-level projected item is a content-column leak only if,
    // once trimmed, it is *exactly* a bare or table-qualified star -- `*`,
    // `n.*`, or `n .*` with arbitrary space around the dot. `COUNT(*)` never
    // matches this because of the surrounding `count(` / `)`.
    private val STAR_ITEM = Regex("""^(?:[a-z_][a-z0-9_]*\s*\.\s*)?\*$""")

    // Splits on commas that sit at paren depth 0 relative to the start of the
    // given string -- i.e. it will not split inside `(SELECT COUNT(*) FROM t)`
    // or an `IN (a, b)` list. Callers only ever pass a substring already known
    // to be internally balanced (the whole statement passed
    // hasUnbalancedParens first), so this never needs to handle negative depth.
    private fun splitTopLevel(s: String): List<String> {
        val items = mutableListOf<String>()
        var depth = 0
        var start = 0
        for (idx in s.indices) {
            when (s[idx]) {
                '(' -> depth++
                ')' -> depth--
                ',' -> if (depth == 0) {
                    items.add(s.substring(start, idx))
                    start = idx + 1
                }
            }
        }
        items.add(s.substring(start))
        return items
    }

    private fun boundaryBefore(text: String, pos: Int) =
        pos <= 0 || (!text[pos - 1].isLetterOrDigit() && text[pos - 1] != '_')
    private fun boundaryAfter(text: String, pos: Int) =
        pos >= text.length || (!text[pos].isLetterOrDigit() && text[pos] != '_')
    private fun keywordAt(text: String, pos: Int, word: String) =
        pos + word.length <= text.length &&
            text.regionMatches(pos, word, 0, word.length) &&
            boundaryBefore(text, pos) &&
            boundaryAfter(text, pos + word.length)

    /**
     * The projection: the raw text between `select` and the statement's
     * *top-level* `from` — the one that actually determines what the outer
     * SELECT reads, as opposed to one nested inside a parenthesised
     * subquery embedded in the projection itself (depth > 0), which must be
     * skipped when locating this boundary. Returns `null` if no top-level
     * FROM is found, or if depth ever goes negative during the scan (which
     * should not happen once [hasUnbalancedParens] has already passed on
     * the whole statement, but is treated as a hard parse failure rather
     * than continuing with a depth counter that can no longer be trusted).
     */
    private fun findTopLevelProjection(masked: String): String? {
        val selectEnd = SELECT_START.find(masked)?.range?.last?.plus(1) ?: return null
        val n = masked.length

        var depth = 0
        var j = selectEnd
        while (j < n) {
            when (masked[j]) {
                '(' -> depth++
                ')' -> {
                    depth--
                    if (depth < 0) return null
                }
            }
            if (depth == 0 && keywordAt(masked, j, "from")) {
                return masked.substring(selectEnd, j)
            }
            j++
        }
        return null
    }

    /**
     * A comma join can hide inside *any* `FROM` in the statement, not just
     * the outermost one — including one nested inside a WHERE/HAVING
     * subquery, or one nested inside a subquery embedded in the projection.
     * Every occurrence of the `from` keyword gets its own independent scan
     * of its own local table clause, starting its own depth counter at 0
     * from right after that particular `from`: the scan for one occurrence
     * ends either at a stop word (where/group/order/limit) found at that
     * occurrence's own depth 0, or when depth goes negative (meaning the
     * scan has exited back through the paren that was enclosing this
     * particular `from`, i.e. reached the end of its own clause). A comma
     * found at depth 0 during any one occurrence's scan is a comma join,
     * regardless of where in the statement that `from` sits.
     */
    private fun hasCommaInAnyFromClause(masked: String): Boolean {
        for (match in FROM_KEYWORD.findAll(masked)) {
            var depth = 0
            var i = match.range.last + 1
            while (i < masked.length) {
                val c = masked[i]
                when (c) {
                    '(' -> depth++
                    ')' -> {
                        depth--
                        if (depth < 0) break
                    }
                }
                if (depth == 0) {
                    if (c == ',') return true
                    if (CLAUSE_STOP_WORDS.any { keywordAt(masked, i, it) }) break
                }
                i++
            }
        }
        return false
    }

    /**
     * SQLite's grammar allows `table-or-subquery := ( join-clause )`, and `,`
     * is itself a join operator — so `JOIN (notifications, android_metadata)`
     * is a parenthesised join clause naming a second, entirely unvetted
     * table, and neither the comma-join scan above (which only looks inside
     * a `FROM` keyword's own clause) nor [FROM_OR_JOIN] (which requires a
     * bare identifier immediately after `from`/`join`, not a `(`) ever sees
     * it. Rather than teach either of those checks about this grammar rule,
     * a `(` directly following `from`/`join` is only ever permitted when the
     * first keyword inside it — after skipping whitespace and any further
     * immediately-nested `(` (the doubly-parenthesised form) — is `select`,
     * i.e. an ordinary subquery. Anything else (a bare table list, an alias,
     * another join clause) is rejected outright.
     */
    private fun hasNonSubqueryParenAfterFromOrJoin(masked: String): Boolean {
        for (match in FROM_OR_JOIN_PAREN.findAll(masked)) {
            var idx = match.range.last + 1 // just past the '(' this match ended on
            while (idx < masked.length && (masked[idx].isWhitespace() || masked[idx] == '(')) {
                idx++
            }
            if (!keywordAt(masked, idx, "select")) return true
        }
        return false
    }

    fun validate(raw: String, allowContent: Boolean): SqlVerdict {
        val sql = raw.trim().replace(FENCE, "").trim().removeSuffix(";").trim()

        if (sql.isEmpty()) return SqlVerdict.Rejected("Empty statement")

        // Comments can hide a second statement from a naive split, and nothing
        // legitimate here needs them.
        if (sql.contains("--") || sql.contains("/*")) {
            return SqlVerdict.Rejected("Comments are not permitted")
        }
        if (sql.contains(";")) {
            return SqlVerdict.Rejected("Only a single statement is permitted")
        }
        if (sql.any { it in QUOTE_CHARS }) {
            return SqlVerdict.Rejected("Quoted or bracketed identifiers (\", `, [, ]) are not permitted")
        }

        val lower = sql.lowercase()
        val masked = maskLiterals(lower)

        if (hasUnbalancedParens(masked)) {
            return SqlVerdict.Rejected("Unbalanced parentheses")
        }

        if (!SELECT_START.containsMatchIn(lower)) {
            return SqlVerdict.Rejected("Only SELECT statements are permitted")
        }
        FORBIDDEN_PATTERNS.firstOrNull { (_, pattern) -> pattern.containsMatchIn(masked) }
            ?.let { (word, _) -> return SqlVerdict.Rejected("Forbidden keyword: $word") }

        COMPOUND_PATTERNS.firstOrNull { (_, pattern) -> pattern.containsMatchIn(masked) }
            ?.let { (word, _) ->
                return SqlVerdict.Rejected("Compound statements ($word) are not supported; only a single SELECT is permitted")
            }

        if (hasCommaInAnyFromClause(masked)) {
            return SqlVerdict.Rejected("Comma joins are not supported; use JOIN")
        }

        if (hasNonSubqueryParenAfterFromOrJoin(masked)) {
            return SqlVerdict.Rejected("A parenthesised join clause is not supported; only a subquery is permitted after FROM/JOIN")
        }

        val tables = FROM_OR_JOIN.findAll(masked).map { it.groupValues[1] }.toSet()
        if (tables.isEmpty()) return SqlVerdict.Rejected("No table referenced")
        (tables - KNOWN_TABLES).firstOrNull()
            ?.let { return SqlVerdict.Rejected("Unknown table: $it") }

        if (!allowContent) {
            val projection = findTopLevelProjection(masked)
                ?: return SqlVerdict.Rejected("Could not determine the SELECT projection")
            val body = QUANTIFIER_PREFIX.replaceFirst(projection, "")
            val isStarProjection = splitTopLevel(body).any { STAR_ITEM.matches(it.trim()) }
            if (isStarProjection) {
                return SqlVerdict.Rejected("SELECT * would expose notification content")
            }
            CONTENT_COLUMNS.firstOrNull { Regex("""\b$it\b""").containsMatchIn(masked) }
                ?.let { return SqlVerdict.Rejected("Column '$it' holds notification content") }
        }

        if (LIMIT_KEYWORD.findAll(masked).count() != 1) {
            return SqlVerdict.Rejected("Exactly one LIMIT clause is required")
        }
        val limitMatch = LIMIT_CLAUSE.find(masked)
            ?: return SqlVerdict.Rejected("LIMIT must be the final clause, as LIMIT <n> optionally followed by OFFSET <n>")
        val limit = limitMatch.groupValues[1].toIntOrNull()
            ?: return SqlVerdict.Rejected("A LIMIT is required")
        if (limit > MAX_LIMIT) return SqlVerdict.Rejected("LIMIT must be at most $MAX_LIMIT")

        return SqlVerdict.Allowed(sql)
    }
}
